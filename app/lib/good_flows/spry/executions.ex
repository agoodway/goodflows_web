defmodule GoodFlows.Spry.Executions do
  @moduledoc """
  Application-owned registry of live run executions on this node.

  A worker registers its process under the run's opaque `owner_id` when it
  claims a run, and records the pids of the local action tasks and SDK
  command processes it starts. Registry entries disappear when the worker
  process exits, so a missing entry on the owner's node means the owner is
  gone. `stop/2` kills a live execution together with its tracked pids and
  confirms that every one of them has terminated.

  Owner ids have the form `"<node>|<boot_id>|<uuid>"`. `boot_id/0` is a
  random id generated once per VM boot, so two instances that share a node
  name (for example several undistributed `:nonode@nohost` instances, or a
  node and its own previous incarnation) never mistake each other's runs for
  local ones. `owner_location/1` recovers the node and boot id so the reaper
  can ask the right node.
  """

  @registry GoodFlows.Spry.ExecutionRegistry
  @boot_id_key {__MODULE__, :boot_id}

  @doc "Child spec for the underlying `Registry`."
  @spec child_spec(term()) :: Supervisor.child_spec()
  def child_spec(_arg) do
    _ = boot_id()
    Registry.child_spec(keys: :unique, name: @registry)
  end

  @doc """
  This VM's boot id: random, generated on first use and kept in
  `:persistent_term` for the life of the VM.
  """
  @spec boot_id() :: String.t()
  def boot_id do
    case :persistent_term.get(@boot_id_key, nil) do
      nil ->
        id = 8 |> :crypto.strong_rand_bytes() |> Base.encode16(case: :lower)
        :persistent_term.put(@boot_id_key, id)
        id

      id ->
        id
    end
  end

  @doc "Generates a fresh owner id bound to the current node and boot."
  @spec new_owner_id() :: String.t()
  def new_owner_id, do: "#{owner_prefix()}#{Ecto.UUID.generate()}"

  @doc "The prefix shared by every owner id generated by this node and boot."
  @spec owner_prefix() :: String.t()
  def owner_prefix, do: "#{node()}|#{boot_id()}|"

  @doc """
  The node and boot id encoded in an owner id. The node is `nil` when the id
  cannot be parsed or names a node this VM has never known (its atom does
  not exist).
  """
  @spec owner_location(String.t() | nil) :: {node() | nil, String.t() | nil}
  def owner_location(owner_id) when is_binary(owner_id) do
    case String.split(owner_id, "|") do
      [node_name, boot, uuid] when node_name != "" and boot != "" and uuid != "" ->
        {existing_atom(node_name), boot}

      _ ->
        {nil, nil}
    end
  end

  def owner_location(_owner_id), do: {nil, nil}

  @doc "The node encoded in an owner id (see `owner_location/1`)."
  @spec owner_node(String.t() | nil) :: node() | nil
  def owner_node(owner_id), do: owner_id |> owner_location() |> elem(0)

  @doc "Whether `owner_id` was generated by this node during this boot."
  @spec local_owner?(String.t() | nil) :: boolean()
  def local_owner?(owner_id) do
    owner_location(owner_id) == {node(), boot_id()}
  end

  defp existing_atom(name) do
    String.to_existing_atom(name)
  rescue
    ArgumentError -> nil
  end

  @doc "Registers the calling process as the execution for `owner_id`."
  @spec register(String.t()) :: :ok | {:error, {:already_registered, pid()}}
  def register(owner_id) do
    case Registry.register(@registry, owner_id, MapSet.new()) do
      {:ok, _owner} -> :ok
      {:error, reason} -> {:error, reason}
    end
  end

  @doc "Removes the calling process's registration for `owner_id`."
  @spec unregister(String.t()) :: :ok
  def unregister(owner_id), do: Registry.unregister(@registry, owner_id)

  @doc """
  Records `pid` as belonging to the calling execution so `stop/2` can kill it.
  No-op when the caller is not a registered execution.
  """
  @spec track(pid()) :: :ok
  def track(pid) when is_pid(pid), do: update_tracked(&MapSet.put(&1, pid))

  @doc "Forgets a tracked pid."
  @spec untrack(pid()) :: :ok
  def untrack(pid) when is_pid(pid), do: update_tracked(&MapSet.delete(&1, pid))

  defp update_tracked(fun) do
    for key <- Registry.keys(@registry, self()) do
      Registry.update_value(@registry, key, fun)
    end

    :ok
  end

  @doc "Returns the execution pid for `owner_id` on this node, if it is alive."
  @spec lookup(String.t()) :: {:ok, pid()} | :error
  def lookup(owner_id) do
    case Registry.lookup(@registry, owner_id) do
      [{pid, _tracked}] -> {:ok, pid}
      [] -> :error
    end
  end

  @doc """
  Stops the execution registered as `owner_id` on this node.

  Kills the execution process and every tracked action task and command
  process, then waits up to `timeout` ms for each to terminate. Returns
  `:not_running` when no execution is registered, `:stopped` once every
  process is confirmed dead, or `{:error, :not_confirmed}`.
  """
  @spec stop(String.t(), timeout()) :: :not_running | :stopped | {:error, :not_confirmed}
  def stop(owner_id, timeout \\ 5_000) do
    case Registry.lookup(@registry, owner_id) do
      [] ->
        :not_running

      [{pid, tracked}] ->
        if kill_and_confirm([pid | MapSet.to_list(tracked)], timeout),
          do: :stopped,
          else: {:error, :not_confirmed}
    end
  end

  @doc """
  Kills `pids` and waits up to `timeout` ms for all of them to terminate.
  Returns whether every process is confirmed dead.

  `opts[:kill]` replaces the function that signals each pid (default
  `Process.exit(pid, :kill)`); it exists so the unconfirmed path can be
  exercised deterministically.
  """
  @spec kill_and_confirm([pid()], timeout(), keyword()) :: boolean()
  def kill_and_confirm(pids, timeout, opts \\ []) do
    kill = Keyword.get(opts, :kill, &Process.exit(&1, :kill))

    refs =
      pids
      |> Enum.uniq()
      |> Enum.map(fn pid ->
        ref = Process.monitor(pid)
        kill.(pid)
        ref
      end)

    deadline = System.monotonic_time(:millisecond) + timeout
    Enum.all?(refs, &await_down(&1, deadline))
  end

  defp await_down(ref, deadline) do
    remaining = max(deadline - System.monotonic_time(:millisecond), 0)

    receive do
      {:DOWN, ^ref, :process, _pid, _reason} -> true
    after
      remaining ->
        Process.demonitor(ref, [:flush])
        false
    end
  end
end
